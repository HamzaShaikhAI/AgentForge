/**
 * Retrieve all curated MCP presets.
 */
export function getCuratedPresets(): McpPreset[] {
  return [...CURATED_MCP_PRESETS];
}

/**
 * Find a curated preset by unique identifier.
 */
export function getPresetById(id: string): McpPreset | undefined {
  return CURATED_MCP_PRESETS.find(p => p.id === id);
}

/**
 * Filter or search curated presets by text query and category.
 */
export function searchPresets(query?: string, category?: string): McpPreset[] {
  return CURATED_MCP_PRESETS.filter(p => {
    if (category && category !== 'all' && p.category !== category) {
      return false;
    }
    if (!query || !query.trim()) {
      return true;
    }
    const q = query.toLowerCase().trim();
    const searchable = `${p.id} ${p.name} ${p.displayName} ${p.description} ${p.category} ${p.package}`.toLowerCase();
    return searchable.includes(q);
  });
}

/**
 * Instantiate an McpServerConfig from a curated preset with user overrides.
 */
export function presetToMcpConfig(
  preset: McpPreset,
  options?: {
    customArgs?: string[];
    env?: Record<string, string>;
    customPort?: number;
  },
): McpServerConfig {
  const mergedArgs = [...preset.args, ...(options?.customArgs || [])];
  return {
    id: preset.id,
    name: preset.displayName,
    description: preset.description,
    transport: preset.transport,
    command: preset.command,
    args: mergedArgs,
    env: options?.env || {},
    autoConnect: false,
    timeoutMs: 20000,
  };
}
